#!/usr/bin/env python3
"""Deterministically optimize four animal-indivisible folds from the v2 manifest."""
import argparse, csv, json, math, random
from collections import defaultdict
from pathlib import Path

METRICS=("frames","mes0","mes1","mes2","mes3")

def main():
    p=argparse.ArgumentParser();p.add_argument("--manifest",type=Path,required=True);p.add_argument("--output-dir",type=Path,required=True);p.add_argument("--iterations",type=int,default=300000);a=p.parse_args()
    with a.manifest.open(newline="",encoding="utf-8") as h: rows=list(csv.DictReader(h))
    stats=defaultdict(lambda:dict.fromkeys(METRICS,0)); videos=defaultdict(set)
    for r in rows:
        x=r["anonymized_animal_id"];stats[x]["frames"]+=1;videos[x].add(r["video_id"])
        for c in range(4):stats[x][f"mes{c}"]+=int(r["mes_polygon_count"] if False else 0)
        # Count polygon instances by reading the per-image class-presence-independent label later is unnecessary here;
        # use class-specific polygon totals reconstructed from labels via semicolon presence only would be wrong.
    # Reconstruct exact polygon counts from sibling per-animal summary generated by the canonical builder.
    summary_path=a.manifest.parent.parent/"analysis/per_animal_summary.csv"
    with summary_path.open(newline="",encoding="utf-8") as h:
        for r in csv.DictReader(h):
            x=r["anonymized_animal_id"]
            for c in range(4):stats[x][f"mes{c}"]=int(r[f"class_{c}_polygons"])
    animals=sorted(stats);totals={m:sum(stats[x][m] for x in animals) for m in METRICS};targets={m:totals[m]/4 for m in METRICS}
    def score(assign):
        folds=[dict.fromkeys(METRICS,0) for _ in range(4)]
        for x,f in assign.items():
            for m in METRICS:folds[f][m]+=stats[x][m]
        return sum(((folds[f][m]-targets[m])/max(targets[m],1))**2 for f in range(4) for m in METRICS),folds
    rng=random.Random(20260818);best=None
    for _ in range(a.iterations):
        assign={x:rng.randrange(4) for x in animals}
        if len(set(assign.values()))<4:continue
        s,folds=score(assign)
        if best is None or s<best[0]:best=(s,assign.copy(),folds)
    s,assign,folds=best;output=[]
    for f in range(4):
        aa=sorted(x for x in animals if assign[x]==f);vv=sorted(v for x in aa for v in videos[x]);output.append({"fold":f+1,"animals":aa,"videos":vv,**folds[f]})
    # Automated leakage assertion: every animal and every video maps to exactly one fold.
    assert sorted(x for z in output for x in z["animals"])==animals
    assert len({x for z in output for x in z["animals"]})==len(animals)
    all_v=[v for z in output for v in z["videos"]];assert len(all_v)==len(set(all_v))==25
    result={"seed":20260818,"iterations":a.iterations,"objective":s,"animal_indivisibility_assertion":True,"video_uniqueness_assertion":True,"totals":totals,"targets":targets,"folds":output}
    a.output_dir.mkdir(parents=True,exist_ok=True);(a.output_dir/"recommended_animal_grouped_folds.json").write_text(json.dumps(result,indent=2),encoding="utf-8")
    with (a.output_dir/"recommended_animal_grouped_folds.csv").open("w",newline="",encoding="utf-8") as h:
        fields=["fold","animals","videos",*METRICS];w=csv.DictWriter(h,fieldnames=fields);w.writeheader()
        for z in output:w.writerow({**z,"animals":";".join(z["animals"]),"videos":";".join(z["videos"])})
    print(json.dumps(result,indent=2))
if __name__=="__main__":main()
